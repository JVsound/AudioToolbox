classdef feaimport
    %FEAIMPORT Summary of this class goes here
    %   Detailed explanation goes here

	properties
		xdot	(1,1)	double	{mustBeNonnegative}				= 0;		% Diaphragm velocity in [m/s]
		sd		(1,1)	double	{mustBeNonnegative}				= 0;		% Diaphragm area in [m2]
		fnamediaphragmf	(1,1)	string							= "";		% Filename including location for pressure results diaphragm front
		fnamediaphragmr	(1,1)	string							= "";		% Filename including location for pressure results diaphragm rear
		fnamexdottopres (1,1)	string							= "";		% Filename including location for pressure at microphone location
		fnamemicff		(1,1)	string							= "";		% Filename including location for pressure result beyond the mesh domain
	end

	properties (Dependent)
		fans																% Frequencies in ANSYS result files.
