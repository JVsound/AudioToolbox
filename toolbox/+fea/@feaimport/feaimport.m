		zarear																% Acoustic impedance rear side of diaphragm
		xdot2pres															% Pressure at specific location at 1m/s diaphragm velocity
		xdot2presff															% Pressure at specific location at 1m/s diaphragm velocity (Far-field)
	end

    methods
        function obj = feaimport
            %FEAIMPORT Construct an instance of this class
            %   Detailed explanation goes here
		end
		function val = get.zafront(obj)
			%ZAFRONT

			% Import pressure results:
			imp		= fea.feaimport.importansyspres(obj.fnamediaphragmf);

			% Obtain complex pressure:
			p		= imp.RealPa + 1i * imp.ImaginaryPa;

			% Volume velocity:
			Q		= obj.xdot * obj.sd;

			% Acoustic impedance:
			val		= (p / Q).';
		end
		function val = get.zarear(obj)
			%ZAREAR

			% Import pressure results:
			imp		= fea.feaimport.importansyspres(obj.fnamediaphragmr);

			% Obtain complex pressure:
			p		= imp.RealPa + 1i * imp.ImaginaryPa;

			% Volume velocity:
			Q		= -obj.xdot * obj.sd;

			% Acoustic impedance:
			val		= (p / Q).';
		end
		function val = get.fans(obj)
			%FANS ANSYS frequency

			% Import pressure results front and rear side of diaphragm:
			if obj.fnamediaphragmf ~= ""
				impf	= fea.feaimport.importansyspres( ...
					obj.fnamediaphragmf);
				ff		= impf.FrequencyHz;
				val		= ff.';
			end
			
			if obj.fnamediaphragmr ~= ""
				impr	= fea.feaimport.importansyspres( ...
					obj.fnamediaphragmr);
				fr		= impr.FrequencyHz;
				val		= fr.';
			end

		end
		function val = get.xdot2pres(obj)
			%XDOT2PRES

			% Import pressure results:
			imp		= fea.feaimport.importansyspres(obj.fnamexdottopres);

			% Obtain complex pressure:
			p		= imp.RealPa + 1i * imp.ImaginaryPa;

			% Pressure at 1m/s diaphragm velocity:
			val		= (p / obj.xdot).';
		end
		function val = get.xdot2presff(obj)
			%XDOT2PRESFF Diaphragm velocity to pressure in the far field.

			% Import pressure results:
			imp		= fea.feaimport.importansyspresff(obj.fnamemicff).FarfieldMaxPresPa;

			% Pressure at 1m/s diaphragm velocity:
			val		= (imp ./ obj.xdot).';
		end
	end

